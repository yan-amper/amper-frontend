/**
 * Единственный источник правды по брейкпоинтам.
 *
 * Медиазапросы не умеют читать CSS-переменные (условие вычисляется до
 * каскада), поэтому брейкпоинты живут в TS, а не в токенах.
 * Использовать только через `media`, литералы `@media (max-width: ...)`
 * в компонентах не писать.
 */
export const bp = {
  /** самые узкие телефоны (320–340): в шапке остаётся только иконка звонка */
  xxs: 340,
  /** очень узкие телефоны — плитки уходят в одну колонку */
  xs: 400,
  /** телефоны */
  sm: 550,
  /** крупные телефоны / граница мобильной навигации */
  md: 768,
  /** планшеты — каталог теряет боковую колонку фильтров */
  lg: 1024,
  /** узкий десктоп — десктопной навигации становится тесно */
  nav: 900,
  /** ширина контентного контейнера */
  xl: 1280,
} as const;

export const media = {
  xxs: `@media (max-width: ${bp.xxs}px)`,
  xs: `@media (max-width: ${bp.xs}px)`,
  sm: `@media (max-width: ${bp.sm}px)`,
  md: `@media (max-width: ${bp.md}px)`,
  lg: `@media (max-width: ${bp.lg}px)`,
  nav: `@media (max-width: ${bp.nav}px)`,
  /** только планшет: между md и lg */
  tablet: `@media (max-width: ${bp.lg}px) and (min-width: ${bp.md + 1}px)`,
  /** десктоп: от lg и шире */
  lgUp: `@media (min-width: ${bp.lg}px)`,
  /**
   * Низкое окно: панель фильтров каталога в него не помещается целиком.
   * Единственный запрос по высоте на весь сайт — отсюда и явное имя.
   */
  shortViewport: `@media (max-height: 760px)`,
  mdUp: `@media (min-width: ${bp.md + 1}px)`,
} as const;
